    <h1>Privacy Policy</h1>
    <p><strong>DLIS (Digital Legislative Information System)</strong> – LGU Damulog<br>Last updated: September 30, 2026</p>

    <h2>What DLIS is</h2>
    <p>DLIS is a system used by authorized personnel of LGU Damulog to store and manage legislative records such as ordinances, resolutions, minutes, and committee reports.</p>

    <h2>Information we collect</h2>
    <ul>
        <li>Account information: username and role, assigned by a system administrator.</li>
        <li>Records and documents uploaded by authorized users.</li>
        <li>Audit logs of actions performed in the system (e.g. record created, updated, exported).</li>
    </ul>

    <h2>Google user data</h2>
    <p>When an administrator connects a Google account, DLIS requests access to Google Drive solely to upload, store, and retrieve the legislative documents managed in DLIS. DLIS does not access, read, or modify any other files in the connected account.</p>
    <p>DLIS's use and transfer of information received from Google APIs adheres to the <a href="https://developers.google.com/terms/api-services-user-data-policy">Google API Services User Data Policy</a>, including the Limited Use requirements.</p>

    <h2>How we use information</h2>
    <p>Information is used only to operate DLIS: authenticating users, storing and displaying legislative records, and keeping an audit trail. We do not sell your data, use it for advertising, or share it with third parties, except as required by law.</p>

    <h2>Storage, security, and retention</h2>
    <p>Data is stored on secured servers, and access is limited to authorized personnel based on their assigned role. Passwords are stored hashed. Records are retained as long as needed for LGU legislative record-keeping, and audit logs are retained for accountability.</p>

    <h2>Revoking access and deleting data</h2>
    <p>You can revoke DLIS's access to your Google account at any time at <a href="https://myaccount.google.com/permissions">myaccount.google.com/permissions</a>. To request deletion of your account or data, contact us at the email below.</p>

